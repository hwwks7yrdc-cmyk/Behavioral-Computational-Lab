class Comprehension(Page):
    form_model = 'player'
    form_fields = ['q1', 'q2', 'q3', 'q4']

    @staticmethod
    def is_displayed(player: Player):
        return player.round_number == 1

    @staticmethod
    def error_message(player: Player, values):
        errors = {
            key: 'Not correct. Please re-read the instructions and try again.'
            for key, answer in C.QUIZ_ANSWERS.items()
            if values[key] is None or abs(values[key] - answer) > 0.005
        }
        if errors:
            player.quiz_failed_attempts += 1
            if player.quiz_failed_attempts >= C.QUIZ_MAX_ATTEMPTS:
                # let the participant continue; the correct answers are explained on the next page
                player.quiz_gave_up = True
                return None
            return errors


