class Results(Page):
    @staticmethod
    def vars_for_template(player: Player):
        members = []
        for o in player.group.get_players():
            members.append(
                dict(
                    id=o.id_in_group,
                    you=o.id_in_group == player.id_in_group,
                    contribution=o.contribution,
                )
            )
        return dict(members=members, history=history(player) if C.SHOW_HISTORY else [])


class FinalResults(Page):
    @staticmethod
    def is_displayed(player: Player):
        return player.round_number == C.NUM_ROUNDS

    @staticmethod
    def vars_for_template(player: Player):
        participant = player.participant
        return dict(
            paying_round=player.session.vars.get('paying_round'),
            total_points=participant.payoff,
            total_money=participant.payoff_plus_participation_fee(),
        )


