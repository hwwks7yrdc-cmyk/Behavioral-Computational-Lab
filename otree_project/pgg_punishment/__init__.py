# ---------------------------------------------------------------- session setup
def creating_session(subsession: Subsession):
    if subsession.round_number == 1:
        subsession.group_randomly()
        if C.PAYMENT_RULE == 'random_round':
            subsession.session.vars['paying_round'] = random.randint(1, C.NUM_ROUNDS)
    elif C.MATCHING == 'stranger':
        subsession.group_randomly()
    else:
        subsession.group_like_round(1)


# ---------------------------------------------------------------- payoffs
def set_stage1(group: Group):
    players = group.get_players()
    total = sum(p.contribution for p in players)
    group.total_contribution = total
    group.threshold_met = (not C.THRESHOLD) or total >= C.THRESHOLD_AMOUNT
    share = C.MPCR * total if group.threshold_met else 0.0
    group.individual_share = round(share, 2)
    bonus = C.BONUS if (C.THRESHOLD and group.threshold_met) else 0
    for p in players:
        if C.THRESHOLD and not group.threshold_met and C.REFUND:
            kept = C.ENDOWMENT
        else:
            kept = C.ENDOWMENT - p.contribution
        p.stage1_earnings = round(kept + share + bonus + 0.0, 2)


def points_assigned(sender: Player, receiver: Player) -> int:
    if sender.id_in_group == receiver.id_in_group:
        return 0
    return getattr(sender, 'punish_%d' % receiver.id_in_group) or 0


def set_final(group: Group):
    players = group.get_players()
    for p in players:
        given = sum(points_assigned(p, o) for o in players)
        received = sum(points_assigned(o, p) for o in players)
        p.punishment_given = given
        p.punishment_received = received
        value = p.stage1_earnings - C.PUNISH_COST * given - C.PUNISH_IMPACT * received
        if C.FLOOR_AT_ZERO:
            value = max(value, 0.0)
        p.round_earnings = round(value + 0.0, 2)
        if C.PAYMENT_RULE == 'all_rounds':
            p.is_paying_round = True
        else:
            p.is_paying_round = p.round_number == p.session.vars['paying_round']
        p.payoff = cu(p.round_earnings) if p.is_paying_round else cu(0)


def history(player: Player):
    rows = []
    for past in player.in_all_rounds():
        earnings = past.field_maybe_none('round_earnings')
        if earnings is None:
            continue
        rows.append(
            dict(
                round=past.round_number,
                contribution=past.contribution,
                total=past.group.total_contribution,
                earnings=earnings,
            )
        )
    return rows


